export function computeLocalStats(cams: Camera[] = INITIAL_CAMERAS): DashboardStats {
  const total = cams.length;
  const live = cams.filter((c) => c.status === 'LIVE').length;
  const offline = cams.filter((c) => c.status === 'OFFLINE').length;
  const regions = new Set(cams.map((c) => c.region)).size;

  const typeCounts: Record<string, number> = {};
  cams.forEach((c) => {
    typeCounts[c.camera_type] = (typeCounts[c.camera_type] || 0) + 1;
  });

  return {
    total_cameras: total,
    live_cameras: live,
    offline_cameras: offline,
    regions_covered: regions,
    last_system_update: new Date().toISOString(),
    health_index_pct: total > 0 ? Math.round((live / total) * 100) : 100,
  };
}

export function computeLocalRegions(cams: Camera[] = INITIAL_CAMERAS) {
  const map: Record<string, { total: number; live: number }> = {};
  cams.forEach((c) => {
    if (!map[c.region]) {
      map[c.region] = { total: 0, live: 0 };
    }
    map[c.region].total += 1;
    if (c.status === 'LIVE') {
      map[c.region].live += 1;
    }
  });

  return Object.entries(map).map(([region, data]) => ({
    region,
    total: data.total,
    live: data.live,
  }));
}
